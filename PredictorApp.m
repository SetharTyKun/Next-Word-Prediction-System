% ============================================
% PredictorApp.m
% Khmer Next Word Prediction - GUI App
% ============================================

function PredictorApp()

% ============================================
% Load Model
% ============================================
loaded     = load('Model.mat');
vocab      = loaded.vocab;
bigramProb = loaded.bigramProb;

% ============================================
% Colors
% ============================================
bgColor     = [28  28  30]  / 255;   % #1C1C1E dark background
accentBlue  = [59  130 246] / 255;   % #3B82F6 blue
resultGreen = [52  211 153] / 255;   % #34D399 green
white       = [255 255 255] / 255;
grayText    = [160 160 165] / 255;
cardColor   = [44  44  46]  / 255;

% ============================================
% Main Window
% ============================================
fig = figure( ...
    'Name', 'Khmer Next Word Predictor', ...
    'NumberTitle', 'off', ...
    'Color', bgColor, ...
    'Position', [400 200 500 520], ...
    'Resize', 'off', ...
    'MenuBar', 'none', ...
    'ToolBar', 'none');

% ============================================
% Title
% ============================================
uicontrol(fig, ...
    'Style', 'text', ...
    'String', 'Khmer Next Word Prediction', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 16, ...
    'FontWeight', 'bold', ...
    'ForegroundColor', white, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 450 400 40], ...
    'HorizontalAlignment', 'center');

% ============================================
% Subtitle
% ============================================
uicontrol(fig, ...
    'Style', 'text', ...
    'String', 'Bigram Model', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 11, ...
    'ForegroundColor', grayText, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 425 400 25], ...
    'HorizontalAlignment', 'center');

% ============================================
% Input Label
% ============================================
uicontrol(fig, ...
    'Style', 'text', ...
    'String', 'Enter a Khmer word:', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 11, ...
    'ForegroundColor', grayText, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 385 400 25], ...
    'HorizontalAlignment', 'left');

% ============================================
% Input Field
% ============================================
inputField = uicontrol(fig, ...
    'Style', 'edit', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 14, ...
    'ForegroundColor', white, ...
    'BackgroundColor', cardColor, ...
    'Position', [50 345 400 40], ...
    'HorizontalAlignment', 'left');

% ============================================
% Predict Button
% ============================================
uicontrol(fig, ...
    'Style', 'pushbutton', ...
    'String', 'Predict Next Word', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 12, ...
    'FontWeight', 'bold', ...
    'ForegroundColor', white, ...
    'BackgroundColor', accentBlue, ...
    'Position', [50 285 400 45], ...
    'Callback', @onPredict);

% ============================================
% Result Label (small title)
% ============================================
uicontrol(fig, ...
    'Style', 'text', ...
    'String', 'Predicted next word:', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 11, ...
    'ForegroundColor', grayText, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 245 400 25], ...
    'HorizontalAlignment', 'left');

% ============================================
% Result Display (big green text)
% ============================================
resultLabel = uicontrol(fig, ...
    'Style', 'text', ...
    'String', '---', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 28, ...
    'FontWeight', 'bold', ...
    'ForegroundColor', resultGreen, ...
    'BackgroundColor', cardColor, ...
    'Position', [50 175 400 65], ...
    'HorizontalAlignment', 'center');

% ============================================
% Status / Error Message
% ============================================
statusLabel = uicontrol(fig, ...
    'Style', 'text', ...
    'String', '', ...
    'FontName', 'Khmer OS', ...
    'FontSize', 10, ...
    'ForegroundColor', [255 100 100]/255, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 145 400 25], ...
    'HorizontalAlignment', 'center');

% ============================================
% Vocabulary Info at Bottom
% ============================================
uicontrol(fig, ...
    'Style', 'text', ...
    'String', sprintf('Vocabulary: %d words', numel(vocab)), ...
    'FontName', 'Khmer OS', ...
    'FontSize', 10, ...
    'ForegroundColor', grayText, ...
    'BackgroundColor', bgColor, ...
    'Position', [50 30 400 25], ...
    'HorizontalAlignment', 'center');

% ============================================
% Predict Callback Function
% ============================================
    function onPredict(~, ~)

        % Get input text and trim spaces
        inputWord = strtrim(get(inputField, 'String'));

        % Validate: must not be empty
        if isempty(inputWord)
            set(statusLabel, 'String', 'Please enter a word.');
            set(resultLabel, 'String', '---');
            return;
        end

        % Validate: must be exactly one word (no spaces)
        if any(inputWord == ' ')
            set(statusLabel, 'String', 'Please enter ONE word only.');
            set(resultLabel, 'String', '---');
            return;
        end

        % Look up word in vocab
        idx = find(strcmp(vocab, inputWord));

        % Word not found in vocabulary
        if isempty(idx)
            set(statusLabel, 'String', 'Word not found in vocabulary.');
            set(resultLabel, 'String', '---');
            return;
        end

        % Get probability row for this word
        row = bigramProb(idx, :);

        % Check if any prediction exists
        if max(row) == 0
            set(statusLabel, 'String', 'No prediction available.');
            set(resultLabel, 'String', '---');
            return;
        end

        % Find most probable next word
        [~, maxIdx] = max(row);
        nextWord = vocab{maxIdx};

        % Display result and clear error
        set(resultLabel, 'String', nextWord);
        set(statusLabel, 'String', '');
    end

end